// Utility helpers for Exporting Data to Excel (CSV) and Printing/Exporting to PDF

export const exportToExcel = (data, filename = 'MDM_Report') => {
    if (!data || !data.length) {
        alert('No data available to export');
        return;
    }

    // Extract headers
    const headers = Object.keys(data[0]);
    const csvRows = [];

    // Header row
    csvRows.push(headers.join(','));

    // Data rows
    for (const row of data) {
        const values = headers.map(header => {
            const val = row[header] === null || row[header] === undefined ? '' : row[header];
            const escaped = ('' + val).replace(/"/g, '""');
            return `"${escaped}"`;
        });
        csvRows.push(values.join(','));
    }

    const csvString = csvRows.join('\n');
    const blob = new Blob(['\ufeff' + csvString], { type: 'text/csv;charset=utf-8;' });
    const url = URL.createObjectURL(blob);
    const link = document.createElement('a');
    link.setAttribute('href', url);
    link.setAttribute('download', `${filename}_${new Date().toISOString().split('T')[0]}.csv`);
    document.body.appendChild(link);
    link.click();
    document.body.removeChild(link);
};

export const exportToPDF = (title, columns, data, brandName = '') => {
    if (!data || !data.length) {
        alert('No data available to export');
        return;
    }

    const bName = (brandName || '').trim();
    const systemTitle = bName ? (bName.toUpperCase().startsWith('SYSTEM') ? bName.toUpperCase() : `SYSTEM ${bName.toUpperCase()}`) : 'SYSTEM MDM';

    const printWindow = window.open('', '_blank');
    const htmlContent = `
        <!DOCTYPE html>
        <html>
        <head>
            <title>${title} - ${systemTitle} Report</title>
            <style>
                body { font-family: 'Segoe UI', Tahoma, sans-serif; padding: 24px; color: #0f172a; background: #fff; }
                .header-brand { display: flex; items-center: justify-between; border-bottom: 2px solid #4f46e5; padding-bottom: 12px; margin-bottom: 16px; }
                h1 { font-size: 22px; color: #3730a3; text-transform: uppercase; margin: 0; font-weight: 800; }
                .brand-badge { font-size: 13px; font-weight: 700; color: #059669; background: #ecfdf5; border: 1px solid #a7f3d0; padding: 4px 12px; rounded: 8px; }
                p { font-size: 11px; color: #64748b; margin-top: 4px; }
                table { width: 100%; border-collapse: collapse; margin-top: 14px; font-size: 11px; }
                th, td { border: 1px solid #cbd5e1; padding: 8px 10px; text-align: left; }
                th { background-color: #4f46e5; color: white; text-transform: uppercase; font-weight: 700; }
                tr:nth-child(even) { background-color: #f8fafc; }
                .footer { margin-top: 30px; font-size: 10px; text-align: right; color: #94a3b8; border-top: 1px solid #e2e8f0; padding-top: 10px; }
            </style>
        </head>
        <body>
            <div class="header-brand">
                <div>
                    <h1>${systemTitle}</h1>
                    <p>Official System Report &bull; ${title}</p>
                </div>
                <div class="brand-badge">${bName ? `BRAND: ${bName.toUpperCase()}` : 'GLOBAL SYSTEM'}</div>
            </div>
            <p>Generated on: ${new Date().toLocaleString()} | ${systemTitle} Security & Audit Protocol</p>
            <table>
                <thead>
                    <tr>
                        ${columns.map(col => `<th>${col.header}</th>`).join('')}
                    </tr>
                </thead>
                <tbody>
                    ${data.map((row, idx) => `
                        <tr>
                            ${columns.map(col => `<td>${col.cell ? col.cell(row, idx) : (row[col.accessor] || '')}</td>`).join('')}
                        </tr>
                    `).join('')}
                </tbody>
            </table>
            <div class="footer">Confidential ${systemTitle} Report &bull; Generated by Authorized User</div>
            <script>
                window.onload = function() { window.print(); }
            </script>
        </body>
        </html>
    `;

    printWindow.document.write(htmlContent);
    printWindow.document.close();
};
